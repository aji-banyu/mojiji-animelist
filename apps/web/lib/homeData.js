// Cache in-memory untuk meminimalkan beban request
const homeCache = new Map();

function formatStatViews(num) {
  if (!num) return "1.2m";
  if (typeof num === "string") return num;
  if (num >= 1000000) return (num / 1000000).toFixed(1).replace(/\.0$/, "") + "m";
  if (num >= 1000) return (num / 1000).toFixed(0) + "k";
  return num.toString();
}

/**
 * Mengambil data untuk kategori Beranda secara dinamis.
 * @param {'popular' | 'ongoing' | 'completed'} category 
 * @param {'anime' | 'manga'} mediaType 
 * @param {number} page 
 * @param {number} limit 
 */
export async function fetchHomeCategoryData(category, mediaType, page = 1, limit = 12) {
  const cacheKey = `${category}_${mediaType}_${page}_${limit}`;
  if (homeCache.has(cacheKey)) {
    return homeCache.get(cacheKey);
  }

  // Tentukan endpoint publik Jikan API
  let endpoint = "";
  if (category === "popular") {
    endpoint = `https://api.jikan.moe/v4/top/${mediaType}?filter=bypopularity&page=${page}&limit=${limit}`;
  } else if (category === "ongoing") {
    if (mediaType === "anime") {
      endpoint = `https://api.jikan.moe/v4/seasons/now?page=${page}&limit=${limit}`;
    } else {
      endpoint = `https://api.jikan.moe/v4/manga?status=publishing&order_by=popularity&sort=desc&page=${page}&limit=${limit}`;
    }
  } else if (category === "completed") {
    endpoint = `https://api.jikan.moe/v4/${mediaType}?status=complete&order_by=popularity&sort=desc&page=${page}&limit=${limit}`;
  }

  try {
    const res = await fetch(endpoint, {
      method: "GET",
      headers: { "Accept": "application/json" },
      signal: AbortSignal.timeout(4000), // Batas 4 detik agar tidak memblokir UI
    });

    if (res.ok) {
      const json = await res.json();
      if (json && Array.isArray(json.data) && json.data.length > 0) {
        const normalized = json.data.map((item, idx) => {
          const score = typeof item.score === "number" ? item.score.toFixed(1) : "8.2";
          const views = formatStatViews(item.members || item.scored_by);
          const count =
            mediaType === "anime"
              ? item.episodes ? `EPS. ${item.episodes}` : "EPS. ?"
              : item.chapters ? `CH. ${item.chapters}` : "CH. ?";

          return {
            id: item.mal_id,
            malId: item.mal_id,
            title: item.title || item.title_english || "Untitled",
            score,
            views,
            metaCount: count,
            statusBadge: category === "ongoing" ? "UP" : category === "completed" ? "Tamat" : `#${idx + 1 + (page - 1) * limit}`,
            country: "🇯🇵",
            image:
              item.images?.jpg?.large_image_url ||
              item.images?.jpg?.image_url ||
              item.images?.webp?.image_url ||
              "",
          };
        });

        const result = {
          items: normalized,
          pagination: {
            currentPage: page,
            hasNextPage: json.pagination?.has_next_page ?? page < 4,
            totalPages: Math.min(json.pagination?.last_visible_page || 4, 4), // Dibatasi 4 halaman agar sesuai Gambar 3
          },
        };

        homeCache.set(cacheKey, result);
        return result;
      }
    }
  } catch {
    // Jika timeout atau offline, otomatis gunakan fallback
  }

  // Fallback Kurasi
  const fallbackList = FALLBACK_HOME_DATA[mediaType]?.[category] || [];
  const startIdx = (page - 1) * limit;
  const sliced = fallbackList.slice(startIdx, startIdx + limit);
  const items = sliced.length > 0 ? sliced : fallbackList.slice(0, limit);

  const fallbackResult = {
    items,
    pagination: {
      currentPage: page,
      hasNextPage: page < 4,
      totalPages: 4,
    },
  };

  homeCache.set(cacheKey, fallbackResult);
  return fallbackResult;
}

